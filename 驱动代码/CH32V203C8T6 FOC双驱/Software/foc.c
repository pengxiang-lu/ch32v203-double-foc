int32_t fast_sin(int32_t x) 
{
	// 归一化
	while(x>ENCODER_OUTPUT_MAX)
	{
		x-=ENCODER_PRECISION;
	}
	while(x<0)
	{
		x+=ENCODER_PRECISION;
	}
	return foc_output_array[x * ENCODER_TO_ARRAY_RATIO];
}
int32_t fast_cos(int32_t x) 
{
	x=x+ENCODER_PRECISION_4;
	// 归一化
	while(x>ENCODER_OUTPUT_MAX)
	{
		x-=ENCODER_PRECISION;
	}
	while(x<0)
	{
		x+=ENCODER_PRECISION;
	}
	return foc_output_array[x * ENCODER_TO_ARRAY_RATIO];
}
//归一化函数
int32_t normalize(int32_t location_temp)
{
	// 归一化
	while(location_temp>ENCODER_OUTPUT_MAX)
	{
		location_temp -= ENCODER_PRECISION;
	}
	while(location_temp<0)
	{
		location_temp += ENCODER_PRECISION;
	}
	return location_temp;
}
//开方函数,使用改进的牛顿法
uint32_t integer_sqrt(int n) 
{
    if (n <= 0) return 0;
    
    int x = n;
    int y = (x + 1) / 2;  // 初始猜测值
    
    // 迭代直到收敛
    while (y < x) {
        x = y;
        y = (x + n / x) / 2;
    }
    
    return x;
}
void circle_limitation(foc_struct *foc_p,int32_t u_q_duty,int32_t u_d_duty)
{
	uint32_t sum = integer_sqrt(u_q_duty * u_q_duty + u_d_duty * u_d_duty);
	if(sum > MOTOR_DUTY_MAX)			// 如果斜边超过最大值，则进行等比例缩放
	{	
		foc_p->u_q 	= MOTOR_DUTY_MAX*u_q_duty/sum;
		foc_p->u_d	= MOTOR_DUTY_MAX*u_d_duty/sum;
	}
	else
	{
		foc_p->u_q	= u_q_duty;
		foc_p->u_d	= u_d_duty;
	}
}
uint8_t svpwm_transform_table[8] ={0,2,6,1,4,3,5,7};						// N编号转化为真实的扇区编号	
void foc_calculate(foc_struct *foc_p, int32_t now_encoder_data, int32_t u_q_duty,int32_t u_d_duty)
{
	// 计算电角度 
	foc_p->encoder_el = foc_p->motor_rotation_direction*foc_p->motor_pole_pairs*now_encoder_data-foc_p->motor_zero_location;
	// 归一化
	foc_p->encoder_el = normalize(foc_p->encoder_el);
	// u_q,u_d合成矢量圆限幅
	circle_limitation(foc_p,u_q_duty,u_d_duty);	
	// 定义三相输出位置临时变量
	static int32_t location_temp_a = 0;                                                 
    static int32_t location_temp_b = 0;
    static int32_t location_temp_c = 0;
	// 三相角度计算
	location_temp_a = foc_p->encoder_el + ENCODER_PRECISION_2;
	location_temp_b = foc_p->encoder_el + ENCODER_PRECISION_6;
	location_temp_c = foc_p->encoder_el - ENCODER_PRECISION_6;
	// 归一化
	location_temp_a = normalize(location_temp_a);
	location_temp_b = normalize(location_temp_b);
	location_temp_c = normalize(location_temp_c);	
	#if	PWM_MODE == SPWM					// SPWM调制方式		
	// 三相占空比计算，三角自带归一化
	foc_p->u_a = ((foc_p->u_q * fast_sin(location_temp_a) - foc_p->u_d * fast_cos(location_temp_a))>>MOTOR_DUTY_BIT) * ARRAY_TO_OUTPUT_RATIO;
	foc_p->u_b = ((foc_p->u_q * fast_sin(location_temp_b) - foc_p->u_d * fast_cos(location_temp_b))>>MOTOR_DUTY_BIT) * ARRAY_TO_OUTPUT_RATIO;
    foc_p->u_c = ((foc_p->u_q * fast_sin(location_temp_c) - foc_p->u_d * fast_cos(location_temp_c))>>MOTOR_DUTY_BIT) * ARRAY_TO_OUTPUT_RATIO;
	// 输出计算
	foc_p->output_duty[0] = (foc_p->u_a + FOC_MIDDLE_DUTY);
	foc_p->output_duty[1] = (foc_p->u_b + FOC_MIDDLE_DUTY);
	foc_p->output_duty[2] = (foc_p->u_c + FOC_MIDDLE_DUTY);
		
	#elif PWM_MODE == SVPWM_7 ||SVPWM_5		// 采用SVPWM调制
	// 三个参考电压的计算
	foc_p->u_1 = (-(foc_p->u_q * fast_cos(location_temp_a) + foc_p->u_d * fast_sin(location_temp_a))>>MOTOR_DUTY_BIT) * ARRAY_TO_OUTPUT_RATIO;
	foc_p->u_2 = (-(foc_p->u_q * fast_cos(location_temp_c) + foc_p->u_d * fast_sin(location_temp_c))>>MOTOR_DUTY_BIT) * ARRAY_TO_OUTPUT_RATIO;
	foc_p->u_3 = (-(foc_p->u_q * fast_cos(location_temp_b) + foc_p->u_d * fast_sin(location_temp_b))>>MOTOR_DUTY_BIT) * ARRAY_TO_OUTPUT_RATIO;
	
	foc_p->svpwm.sector_num = svpwm_transform_table[(foc_p->u_1>0?1:0) + 2 * (foc_p->u_2>0?1:0) + 4 * (foc_p->u_3>0?1:0)];		// 查表获取具体扇区编号
	
	switch(foc_p->svpwm.sector_num)
	{
		case 1:
			foc_p->svpwm.tx = foc_p->u_2 * SVPWM_K;		// t4
			foc_p->svpwm.ty = foc_p->u_1 * SVPWM_K;		// t6
			break;	
		
		case 2:
			foc_p->svpwm.tx = -foc_p->u_2 * SVPWM_K;	// t2
			foc_p->svpwm.ty = -foc_p->u_3 * SVPWM_K;	// t6
			break;	
		
		case 3:
			foc_p->svpwm.tx = foc_p->u_1 * SVPWM_K;		// t2
			foc_p->svpwm.ty	= foc_p->u_3 * SVPWM_K;		// t3
			break;	
		
		case 4:
			foc_p->svpwm.tx = -foc_p->u_1 * SVPWM_K;	// t1
			foc_p->svpwm.ty = -foc_p->u_2 * SVPWM_K;	// t3
			break;	
		
		case 5:
			foc_p->svpwm.tx = foc_p->u_3 * SVPWM_K;		// t1
			foc_p->svpwm.ty = foc_p->u_2 * SVPWM_K;		// t5
			break;	
			
		case 6:
			foc_p->svpwm.tx = -foc_p->u_3 * SVPWM_K;	// t4
			foc_p->svpwm.ty	= -foc_p->u_1 * SVPWM_K;	// t5
			break;
		
		default:
			foc_p->svpwm.tx = 0;
			foc_p->svpwm.ty = 0;
			break;
	}
	// 防止过调制
	static uint32_t t_sum = 0;
	t_sum = foc_p->svpwm.tx+foc_p->svpwm.ty;
	if(t_sum > foc_p->svpwm.ts)					// 如果有效矢量作用时间之和大于周期
	{
		foc_p->svpwm.tx = foc_p->svpwm.ts*foc_p->svpwm.tx/t_sum;
		foc_p->svpwm.ty = foc_p->svpwm.ts*foc_p->svpwm.ty/t_sum;
	}
	#if	PWM_MODE == SVPWM_5			// 如果是7段式SVPWM调制
	// PWM1模式下的调制
	foc_p->svpwm.ta = foc_p->svpwm.ts>>1;							// 就是满占空比
	foc_p->svpwm.tb = foc_p->svpwm.ta - (foc_p->svpwm.tx>>1); 
	foc_p->svpwm.tc = foc_p->svpwm.tb - (foc_p->svpwm.ty>>1); 
	#elif PWM_MODE == SVPWM_7		// 如果是5段式SVPWM调制
	foc_p->svpwm.ta = (foc_p->svpwm.ts + foc_p->svpwm.tx + foc_p->svpwm.ty)>>2;		
	foc_p->svpwm.tb = foc_p->svpwm.ta - (foc_p->svpwm.tx>>1); 
	foc_p->svpwm.tc = foc_p->svpwm.tb - (foc_p->svpwm.ty>>1); 
	#endif
	switch(foc_p->svpwm.sector_num)
	{
		case 1:
		foc_p->output_duty[0] = foc_p->svpwm.ta;		
		foc_p->output_duty[1] = foc_p->svpwm.tb;
		foc_p->output_duty[2] = foc_p->svpwm.tc;
		break;
		case 2:
		foc_p->output_duty[0] = foc_p->svpwm.tb;		
		foc_p->output_duty[1] = foc_p->svpwm.ta;
		foc_p->output_duty[2] = foc_p->svpwm.tc;
		break;
		case 3:
		foc_p->output_duty[0] = foc_p->svpwm.tc;		
		foc_p->output_duty[1] = foc_p->svpwm.ta;
		foc_p->output_duty[2] = foc_p->svpwm.tb;
		break;
		case 4:
		foc_p->output_duty[0] = foc_p->svpwm.tc;		
		foc_p->output_duty[1] = foc_p->svpwm.tb;
		foc_p->output_duty[2] = foc_p->svpwm.ta;
		break;
		case 5:
		foc_p->output_duty[0] = foc_p->svpwm.tb;		
		foc_p->output_duty[1] = foc_p->svpwm.tc;
		foc_p->output_duty[2] = foc_p->svpwm.ta;
		break;
		case 6:
		foc_p->output_duty[0] = foc_p->svpwm.ta;		
		foc_p->output_duty[1] = foc_p->svpwm.tc;
		foc_p->output_duty[2] = foc_p->svpwm.tb;
		break;
        default:
        foc_p->output_duty[0] = 0;
        foc_p->output_duty[1] = 0;
        foc_p->output_duty[2] = 0;
        break;
	}
	
	#endif
	
}
void foc_init(foc_struct *foc_p,uint32_t motor_pole_pairs, int32_t zero_location, int32_t rotation_direction)
{	
    foc_p->motor_pole_pairs         = motor_pole_pairs;             // 保存当前电机的极对数
    
    foc_p->motor_zero_location      = zero_location;                // 保存当前电机的零点位置
    
    foc_p->motor_rotation_direction = rotation_direction;           // 保存当前电机的旋转方向
	
	foc_p->svpwm.ts 				= OUTPUT_DUTY_MAX * 2;		    // 计算总周期
}





